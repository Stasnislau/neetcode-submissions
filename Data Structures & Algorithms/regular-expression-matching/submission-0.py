class Solution:
    def isMatch(self, s: str, p: str) -> bool:
        m, n = len(s), len(p)
        # dp[i][j] = совпадает ли s[:i] с p[:j]
        dp = [[False] * (n + 1) for _ in range(m + 1)]
        
        # 1. Базовый случай: пустая строка и пустой паттерн совпадают
        dp[0][0] = True
        
        # 2. Базовый случай: пустая строка и НЕпустой паттерн (типа s="", p="a*b*")
        # Звездочка может "обнулить" предыдущую букву, поэтому мы смотрим на 2 шага назад в dp.
        for j in range(2, n + 1):
            if p[j-1] == '*':
                dp[0][j] = dp[0][j-2]
                
        # 3. Понеслась ебанина по матрице
        for i in range(1, m + 1):
            for j in range(1, n + 1):
                
                # Если текущие символы паттерна и строки совпадают (или стоит точка)
                if p[j-1] == s[i-1] or p[j-1] == '.':
                    dp[i][j] = dp[i-1][j-1] # Берем значение по диагонали (как в Edit Distance)
                    
                # Если текущий символ паттерна — это ебаная ЗВЕЗДОЧКА
                elif p[j-1] == '*':
                    # Сценарий А: Звездочка ОБНУЛЯЕТ предыдущий символ паттерна.
                    # Мы смотрим на dp[i][j-2] (как будто 'a*' вообще не было).
                    dp[i][j] = dp[i][j-2]
                    
                    # Сценарий Б: Звездочка ЖРЁТ символ строки.
                    # Это возможно ТОЛЬКО если символ ПЕРЕД звездочкой совпадает с текущим символом строки.
                    if p[j-2] == s[i-1] or p[j-2] == '.':
                        # Если совпадает, мы говорим: результат такой же, как если бы строка была на 1 символ короче
                        dp[i][j] = dp[i][j] or dp[i-1][j]
                        
        return dp[m][n]
